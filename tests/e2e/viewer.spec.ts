import { expect, test } from '@playwright/test'
test('photo fills the viewer with optional tags, album navigation and persistent AI album title', async ({
  page,
}, testInfo) => {
  await page.goto('/#/albums')
  const card = page.getByRole('region', { name: 'AI 智能整理相册' })
  await card.getByRole('button', { name: '体验示例整理', exact: true }).click()
  await card.getByRole('checkbox').first().check()
  await card.getByRole('button', { name: '预览保存 1 个相册' }).click()
  await page.getByRole('button', { name: '确认保存相册' }).click()
  const album = page.locator('.user-album').first()
  const members = await album.locator('small').innerText()
  await album.click()
  await page.getByRole('button', { name: '修改名称', exact: true }).click()
  const rename = page.getByRole('dialog', { name: '修改相册名称' })
  await rename.getByRole('textbox', { name: '相册名称' }).fill('我的 AI 回忆')
  await rename.getByRole('button', { name: '保存名称' }).click()
  await expect(page.getByRole('heading', { name: '我的 AI 回忆', exact: true })).toBeInViewport()
  await page.getByRole('button', { name: '网格查看' }).click()
  await page.locator('.photo-open').first().click()
  const viewer = page.getByRole('dialog', { name: '照片详情' })
  await expect(viewer.getByRole('textbox')).toHaveCount(0)
  await expect(viewer.locator('.viewer-quality')).toHaveText('示例插画')
  const bounds = await viewer.boundingBox(),
    stage = await viewer.locator('.viewer-stage').boundingBox()
  expect(stage!.height / bounds!.height).toBeGreaterThan(0.99)
  expect(stage!.width / bounds!.width).toBeGreaterThan(0.99)
  expect(Math.abs(bounds!.height - page.viewportSize()!.height)).toBeLessThan(2)
  await expect(viewer.locator('img.is-current')).toHaveCSS('object-fit', 'cover')
  await viewer.getByRole('button', { name: '完整显示照片' }).click()
  await expect(viewer.locator('img.is-current')).toHaveCSS('object-fit', 'contain')
  await viewer.getByRole('button', { name: '放大照片' }).click()
  await expect(viewer.locator('.viewer-stage')).toHaveClass(/zoomed/)
  await viewer.getByRole('button', { name: '适应屏幕' }).click()
  const next = viewer.getByRole('button', { name: '下一张照片' })
  if (await next.isEnabled()) {
    const first = await viewer.locator('img.is-current').getAttribute('alt')
    await next.click()
    await expect(viewer.locator('img.is-current')).not.toHaveAttribute('alt', first!)
    await viewer.getByRole('button', { name: '上一张照片' }).click()
    await expect(viewer.locator('img.is-current')).toHaveAttribute('alt', first!)
  }
  await page.screenshot({ path: `test-results/${testInfo.project.name}-viewer.png` })
  await page.keyboard.press('Escape')
  await expect(viewer).toHaveCount(0)
  await expect(page.locator('.photo-open').first()).toBeFocused()
  await page.getByRole('button', { name: '返回相册列表' }).click()
  await page.reload()
  await expect(album).toContainText('我的 AI 回忆')
  await card.getByRole('button', { name: '体验示例整理', exact: true }).click()
  await card.getByRole('checkbox').first().check()
  await card.getByRole('button', { name: '预览保存 1 个相册' }).click()
  await page.getByRole('button', { name: '确认保存相册' }).click()
  await expect(album).toContainText('我的 AI 回忆')
  await expect(album.locator('small')).toHaveText(members)
})
